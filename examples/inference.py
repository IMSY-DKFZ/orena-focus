"""End-to-end inference example for the ORena SAVE FOCUS challenge.

Pipeline:
  1. Load a pre-split FocusDataset (see data_preparation.py for how to create one)
  2. Wrap it in FocusVideoDataset to produce on-the-fly temporary clips
  3. Run a Qwen3-VL model over every test sample
  4. Collect Responses and evaluate with the Evaluator

Prerequisites
-------------
    pip install orena-focus qwen-vl-utils transformers accelerate

The dataset must have been downloaded and split beforehand — see
``examples/data_preparation.py`` for the full preparation pipeline.
"""

import logging
import time
import warnings

import torch
from progiter import ProgIter
from qwen_vl_utils import process_vision_info
from transformers import AutoProcessor, Qwen3VLForConditionalGeneration

from focus import FO_DEFINITIONS_FILE, FocusConfig, set_config
from focus.data.base_dataset import FocusDataset
from focus.data.data_models import Response
from focus.data.video_dataset import FocusVideoDataset, VideoSample
from focus.enums import DatasetSplit, Track
from focus.evaluation.evaluator import Evaluator

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

# ── Configuration ─────────────────────────────────────────────────────
# All tuneable parameters in one place.

CONFIG = {
    "root_dir": "/data/focus",
    "model_id": "Qwen/Qwen3-VL-4B-Instruct",
    "device": "cuda:0" if torch.cuda.is_available() else "cpu",
    "dataset_name": "heico",
    "track": Track.SEGMENT,
    "video_stride": 25,  # keep every 25th frame (1 fps at 25 fps source)
    "video_resolution": (640, 360),
    "use_overlay": True,  # use timestamp-overlaid videos
    "num_eval": 100,  # set to None to evaluate all test samples
    "output_dir": None,  # set to a path to persist results CSV files
}

SYSTEM_PROMPT = (
    "You are a surgical assistant. You are given endoscopic video from a "
    "minimally invasive procedure. Analyze the footage and answer the surgical "
    "question based on the visual evidence. Be precise and concise.\n\n"
    + FO_DEFINITIONS_FILE.read_text()
)


# ── Inference engine ──────────────────────────────────────────────────


class QwenInferenceEngine:
    """Qwen3-VL model wrapper for FOCUS challenge inference.

    Parameters
    ----------
    model_id : str
        HuggingFace model identifier (e.g. ``"Qwen/Qwen3-VL-4B-Instruct"``).
    device : str
        Torch device string (``"cpu"`` or ``"cuda"``).

    Notes
    -----
    Call :meth:`load` before :meth:`predict` to initialise model weights.
    """

    def __init__(self, model_id: str, device: str) -> None:
        self.model_id = model_id
        self.device = device
        self.model = None
        self.processor = None

    def load(self) -> None:
        """Load the processor and model weights from HuggingFace Hub."""
        logger.info(f"Loading model {self.model_id!r} on device {self.device!r}…")
        self.processor = AutoProcessor.from_pretrained(self.model_id)
        self.model = Qwen3VLForConditionalGeneration.from_pretrained(
            self.model_id,
            torch_dtype="auto",
            device_map="auto" if self.device == "cuda" else None,
        ).eval()
        if hasattr(self.model, "generation_config"):
            self.model.generation_config.max_length = None
        logger.info("Model ready.")

    def predict(self, sample: VideoSample) -> str:
        """Run inference on one sample and clean up the temporary clip.

        Parameters
        ----------
        sample : VideoSample
            A sample from :class:`~focus.data.video_dataset.FocusVideoDataset`.
            ``sample.video_path`` is deleted after inference regardless of
            whether the call succeeds.

        Returns
        -------
        str
            The raw text generated by the model, or an error message prefixed
            with ``"Inference Error:"`` if generation fails.
        """
        try:
            messages = [
                {"role": "system", "content": SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "video",
                            "video": f"file://{sample.video_path}",
                            "fps": sample.fps,
                            "video_metadata": {
                                "fps": sample.fps,
                                "width": CONFIG["video_resolution"][0],
                                "height": CONFIG["video_resolution"][1],
                            },
                        },
                        {"type": "text", "text": sample.request.question},
                    ],
                },
            ]

            text = self.processor.apply_chat_template(
                messages, tokenize=False, add_generation_prompt=True
            )
            image_inputs, video_inputs = process_vision_info(messages)
            inputs = self.processor(
                text=[text],
                images=image_inputs,
                videos=video_inputs,
                padding=True,
                return_tensors="pt",
            ).to(self.device)

            with torch.no_grad():
                gen_ids = self.model.generate(**inputs, max_new_tokens=128)
                trimmed = [ids[len(inputs.input_ids[0]) :] for ids in gen_ids]
                return self.processor.batch_decode(trimmed, skip_special_tokens=True)[0]

        except Exception as exc:
            logger.error(f"[{sample.request.qID}] Inference failed: {exc}")
            return f"Inference Error: {str(exc)[:50]}"

        finally:
            sample.video_path.unlink(missing_ok=True)


# ── Main pipeline ─────────────────────────────────────────────────────


def main() -> None:
    # ── 1. Configure and load dataset ────────────────────────────────
    # Run examples/data_preparation.py first to download and split the dataset.
    set_config(FocusConfig(root_dir=CONFIG["root_dir"]))

    base_dataset = FocusDataset(
        dataset=CONFIG["dataset_name"],
        split=DatasetSplit.TEST,
        track=CONFIG["track"],
    )
    test_dataset = FocusVideoDataset(
        base_dataset,
        stride=CONFIG["video_stride"],
        use_overlay=CONFIG["use_overlay"],
        resolution=CONFIG["video_resolution"],
    )

    n_total = len(test_dataset)
    n_eval = min(CONFIG["num_eval"], n_total) if CONFIG["num_eval"] else n_total
    logger.info(f"Evaluating {n_eval}/{n_total} test samples.")

    # ── 2. Load model ─────────────────────────────────────────────────
    engine = QwenInferenceEngine(CONFIG["model_id"], CONFIG["device"])
    engine.load()

    # ── 3. Inference loop ─────────────────────────────────────────────
    requests, references, responses = [], [], []

    for i, sample in enumerate(ProgIter(test_dataset, total=n_eval, desc="Inference")):
        if i >= n_eval:
            break

        t0 = time.perf_counter()
        prediction = engine.predict(sample)
        latency = time.perf_counter() - t0

        requests.append(sample.request)
        references.append(sample.reference)
        responses.append(
            Response(
                qID=sample.request.qID,
                content=prediction,
                latency=latency,
            )
        )

    if not responses:
        warnings.warn("No test samples were processed. Check dataset status.")
        return

    # ── 4. Evaluation ─────────────────────────────────────────────────
    results_df, summary_df = Evaluator(judge_kwargs={"device": CONFIG["device"]}).run(
        requests=requests,
        references=references,
        responses=responses,
        output_dir=CONFIG["output_dir"],
    )

    print(summary_df.to_string(index=False))


if __name__ == "__main__":
    main()
